/* texture coordinates of a cell (s0, t0 top left; s1, t1 bottom right) */
static inline void sofhud_cell(int cell, float *s0, float *t0, float *s1, float *t1)
{
	int col = cell % 16, row = cell / 16;
	*s0 = (float)(col * SOFHUD_CELL) / SOFHUD_TEX_W;
	*t0 = (float)(row * SOFHUD_CELL) / SOFHUD_TEX_H;
	*s1 = (float)((col + 1) * SOFHUD_CELL) / SOFHUD_TEX_W;
	*t1 = (float)((row + 1) * SOFHUD_CELL) / SOFHUD_TEX_H;
}

/* the cell of a character (lower case as capitals, unknown as '?') */
static inline int sofhud_charcell(int c)
{
	if (c >= 'a' && c <= 'z') c -= 'a' - 'A';
	if (c < SOFHUD_FIRST || c >= SOFHUD_FIRST + SOFHUD_COUNT) c = '?';
	return c - SOFHUD_FIRST;
}

